# Prompt the user to insert the first number
first_number = input("Please insert first number: ")

# Prompt the user to insert the second number
second_number = input("Please insert second number: ")

# Convert input to integers
first_number = int(first_number)
second_number = int(second_number)

# Perform addition
result = first_number + second_number

# Print the result
print(f"The sum of {first_number} and {second_number} is: {result}")